	public static List<Vector2> Build(string text, float scale = 0.22f, float tracking = 0.72f)
	{
		var pts = new List<Vector2>(512);
		float x = -(text.Length - 1) * 0.5f * tracking;
		foreach (char ch in text)
		{
			if (Glyphs.TryGetValue(char.ToUpperInvariant(ch), out var strokes))
			{
				foreach (var stroke in strokes)
				{
					for (int i = 0; i < stroke.Length; i++)
					{
						var p = stroke[i];
						pts.Add(new Vector2((p.X + x) * scale, (p.Y - 0.5f) * scale * 1.35f));
					}
					if (stroke.Length > 0)
						pts.Add(pts[^1]);
				}
			}
			x += tracking;
		}
		return PathUtil.Resample(pts, Math.Max(64, pts.Count * 3));
	}

